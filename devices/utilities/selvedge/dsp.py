"""Generate Selvedge's gen~ codebox (gen/selvedge.genexpr).

Selvedge is the finished edge of a cloth; this checks the edge of a note. Max's fzero~
tracks the pitch of the input and sends it in Hz as Param hz; the codebox finds the
nearest step of the Scale (the family's twenty, microtonal ones included), counted from the
Root in octave 3 (C3 = 60; it matters for scales that don't repeat at the
octave, such as Bohlen-Pierce), and
outputs, while hz is above 20:

    out3  cents from that step (-50..+50 in 12-TET, less in finer scales)
    out4  the step's number within the scale (0 is the root), -1 when nothing is heard
    out5  the step's exact pitch, as a MIDI note number with its fraction

Audio passes through untouched (out1, out2). Run build.py, which calls write().
"""

from pathlib import Path

from genlint import branches
from scales import SCALES

HERE = Path(__file__).resolve().parent
OUT = HERE / "gen" / "selvedge.genexpr"
MAXSTEPS = max(len(st) for _, st, _ in SCALES)

PARAMS = f"""\
Param hz(0, min=0, max=20000);
Param root(9, min=0, max=11);
Param scale(2, min=0, max={len(SCALES) - 1});
"""


def scale_fill():
    out = ["sc = floor(scale + 0.5);", "if (sc != scPrev) {", "\tscPrev = sc;"]
    out += branches("sc", [[f"poke(steps, {v:g}, {j});" for j, v in enumerate(st)] + [f"scN = {len(st)};", f"scP = {per:g};"]
                           for _, st, per in SCALES])           # a tree, not 26 'else if' (lib/genlint.py)
    out.append("}")
    return "\n".join(out) + "\n"


def nearest():
    lines = ["best = 0;", "bestIdx = 0;", "bd = 1000;"]
    for j in range(MAXSTEPS + 1):
        cand = f"(({j} < scN) ? peek(steps, {j}) : scP)" if j < MAXSTEPS else "scP"
        idx = f"(({j} < scN) ? {j} : 0)" if j < MAXSTEPS else "0"
        lines += [f"c = {cand};", "if (abs(r - c) < bd) {", "\tbd = abs(r - c);", "\tbest = c;",
                  f"\tbestIdx = {idx};", "}"]
    return "\n".join(lines) + "\n"


def generate(title="Selvedge: how far a note is from the nearest step of the scale"):
    code = f"""
out1 = in1;
out2 = in2;
{scale_fill()}if (hz > 20) {{
\tnote = 69 + 12 * log2(hz / 440);
\trel = note - 60 - floor(root + 0.5);
\toc = floor(rel / scP);
\tr = rel - oc * scP;
{chr(10).join(chr(9) + ln for ln in nearest().splitlines())}
\tout3 = (r - best) * 100;
\tout4 = bestIdx;
\tout5 = 60 + floor(root + 0.5) + oc * scP + best;
}}
else {{
\tout3 = 0;
\tout4 = -1;
\tout5 = 0;
}}
"""
    decl = [f"// {title}. Generated by selvedge/dsp.py; edit that, not this.", "", PARAMS,
            f"Data steps({MAXSTEPS});", "History scPrev(-1);", "History scN(7);", "History scP(12);"]
    return "\n".join(decl) + "\n" + code


def write():
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(generate())
    return OUT
