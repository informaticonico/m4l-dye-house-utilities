"""Selvedge's screens (scripts packed inside the device, lib/visual.py's pattern), v1.0b1's panel
(plans/ideas/utilities-panels.md): the cents meter, flat, and the scale's steps as a strip. Draws only. No word under
7 px.
"""

import json

from m4l import BORDER, CARD, FONT, MUTED, TEXT
from visual import HEAD, SCREEN, rgba


def meter_script(color, lo=-50, hi=50, zone=5):
    """Cents from the nearest step, flat: ticks every 10 cents from lo to hi, a zone around 0 ('in tune'), a mark at
    the value with its cents under it. Messages: value <cents>, idle (nothing heard: no mark)."""
    return f"""// Selvedge's cents meter. Generated by devices/ideas/selvedge/screens.py; edit that, not this.
// Messages: value <cents>, idle. Draws only.
{HEAD}
var C = {rgba(color)}, ZONEC = {rgba(color, 0.25)}, TXT = {rgba(TEXT)}, DIMT = {rgba(MUTED)}, LINE = {rgba(BORDER)};
var LO = {lo}, HI = {hi}, ZONE = {zone}, FONTN = "{FONT}", v = 0, live = 0;

function value(x) {{ v = Math.max(LO, Math.min(HI, x)); live = 1; mgraphics.redraw(); }}
function idle() {{ live = 0; mgraphics.redraw(); }}

function word(x, y, s, size, c) {{
	mgraphics.select_font_face(FONTN);
	mgraphics.set_font_size(size);
	var tw = mgraphics.text_measure(s)[0];
	mgraphics.set_source_rgba(c);
	mgraphics.move_to(x - tw / 2, y);
	mgraphics.show_text(s);
}}

function paint() {{
	var w = mgraphics.size[0], x0 = 10, x1 = w - 10, my = 13;
	function at(c) {{ return x0 + (c - LO) / (HI - LO) * (x1 - x0); }}
	mgraphics.set_source_rgba(ZONEC);
	mgraphics.rectangle_rounded(at(-ZONE), my - 6, at(ZONE) - at(-ZONE), 12, 4, 4);
	mgraphics.fill();
	mgraphics.set_source_rgba(LINE);
	mgraphics.set_line_width(1.2);
	mgraphics.move_to(x0, my);
	mgraphics.line_to(x1, my);
	mgraphics.stroke();
	for (var c = LO; c <= HI; c += 10) {{
		var big = c % 50 == 0, x = at(c);
		mgraphics.set_source_rgba(c == 0 ? TXT : DIMT);
		mgraphics.set_line_width(c == 0 ? 0.8 : 0.6);
		mgraphics.move_to(x, my - (big ? 5 : 3));
		mgraphics.line_to(x, my + (big ? 5 : 3));
		mgraphics.stroke();
	}}
	word(x0, my + 15, "-" + Math.abs(LO), 7, DIMT);
	word(x1, my + 15, "+" + HI, 7, DIMT);
	if (!live) return;
	var nx = at(v), r = Math.round(v), inTune = Math.abs(v) <= ZONE;
	mgraphics.set_source_rgba(inTune ? C : TXT);
	mgraphics.rectangle_rounded(nx - 1.4, my - 9, 2.8, 18, 2, 2);
	mgraphics.fill();
	word(nx, my + 15, (r > 0 ? "+" : (r < 0 ? "-" : "")) + Math.abs(r) + " cents", 7, inTune ? C : TXT);
}}

// for the tests: where the mark is, and whether it's reading
function values() {{ return [v, live]; }}
"""


def steps_script(color, root_color, scales, roots):
    """THE SCALE'S STEPS, FROM THE ROOT: a cell a step, as wide as the step is (where it falls in the scale's period),
    the nearest step lit, the root outlined in its source's colour; the twelve names marked above where they fall (a
    period that isn't the octave: as many as it spans); under the cells the root's number, the nearest's, the last's.
    Messages: root <0..11>, scale <i>, step <k> (-1: nothing heard), kc <r g b a> (the key's source colour)."""
    table = ", ".join(f"[[{', '.join(f'{v:.6g}' for v in st)}], {per:.6g}]" for _, st, per in scales)
    return f"""// Selvedge's steps. Generated by devices/ideas/selvedge/screens.py; edit that, not this.
// Messages: root, scale, step, kc. Draws only.
{HEAD}
var C = {rgba(color)}, RC = {rgba(root_color)}, SCREENC = {rgba(SCREEN)}, CELLC = {rgba(CARD)};
var DIMT = {rgba(MUTED)}, TXT = {rgba(TEXT)}, FONTN = "{FONT}";
var SCALES = [{table}], NAMES = {json.dumps(list(roots))};
var rootPc = 9, sc = 2, now = -1;

function root(r) {{ rootPc = ((Math.floor(r) % 12) + 12) % 12; mgraphics.redraw(); }}
function scale(i) {{ sc = Math.max(0, Math.min(SCALES.length - 1, Math.floor(i))); mgraphics.redraw(); }}
function step(k) {{ now = Math.floor(k); mgraphics.redraw(); }}
function kc(r, g, b, a) {{ RC = [r, g, b, a === undefined ? 1 : a]; mgraphics.redraw(); }}

function word(x, y, s, size, c, anchor) {{
	mgraphics.select_font_face(FONTN);
	mgraphics.set_font_size(size);
	var tw = mgraphics.text_measure(s)[0];
	mgraphics.set_source_rgba(c);
	mgraphics.move_to(anchor == 1 ? x - tw / 2 : x, y);
	mgraphics.show_text(s);
}}

function paint() {{
	var w = mgraphics.size[0], h = mgraphics.size[1], x0 = 6, sw = w - 12;
	var st = SCALES[sc][0], per = SCALES[sc][1], n = st.length;
	function at(p) {{ return x0 + p / per * sw; }}
	mgraphics.set_source_rgba(SCREENC);
	mgraphics.rectangle_rounded(0, 0, w, h, 6, 6);
	mgraphics.fill();
	word(5, 10, "THE SCALE'S STEPS, FROM THE ROOT", 7, DIMT, 0);
	var every = sw / per >= 14 ? 1 : 2;
	for (var k = 0; k < per - 0.01; k += every) {{
		var x = at(k);
		mgraphics.set_source_rgba(DIMT);
		mgraphics.set_line_width(0.6);
		mgraphics.move_to(x, 15);
		mgraphics.line_to(x, 20);
		mgraphics.stroke();
		word(x + 0.5, 28, NAMES[(rootPc + k) % 12], 7, DIMT, 0);
	}}
	for (var k = 0; k < n; k++) {{
		var a = at(st[k]), b = at(k + 1 < n ? st[k + 1] : per);
		mgraphics.set_source_rgba(k == now ? C : CELLC);
		mgraphics.rectangle_rounded(a + 0.6, 32, Math.max(b - a - 1.2, 1), 14, 3, 3);
		mgraphics.fill();
		if (k == 0) {{
			mgraphics.set_source_rgba(RC);
			mgraphics.set_line_width(1);
			mgraphics.rectangle_rounded(a + 0.6, 32, Math.max(b - a - 1.2, 1), 14, 3, 3);
			mgraphics.stroke();
		}}
	}}
	function mid(k) {{ return (at(st[k]) + at(k + 1 < n ? st[k + 1] : per)) / 2; }}
	word(mid(0), 56, "1", 7, RC, 1);
	if (now > 0 && now < n) word(mid(now), 56, String(now + 1), 7, C, 1);
	if (n > 1 && now != n - 1 && mid(n - 1) - mid(Math.max(now, 0)) > 10) word(mid(n - 1), 56, String(n), 7, DIMT, 1);
}}

// for the tests: [steps in the scale, the step lit (-1 none), the names marked]
function values() {{
	var st = SCALES[sc][0], per = SCALES[sc][1], names = [];
	var every = (mgraphics.size[0] - 12) / per >= 14 ? 1 : 2;
	for (var k = 0; k < per - 0.01; k += every) names.push(NAMES[(rootPc + k) % 12]);
	return [st.length, now, names];
}}
"""
