def box_of(p, oid):
    return next(b["box"] for b in p.boxes if b["box"].get("id") == oid)


def steps_words(steps, per):
    """The scale's size, in words short enough for the circle's screen."""
    if per == 12:
        return f"{len(steps)} notes an octave"
    if abs(per - 19.0196) < 0.01:
        return f"{len(steps)} steps a tritave"
    return f"{len(steps)} steps every {per:g} st"


def circle_script(color, scales):
    """The key on a circle (the mockup's): the twelve names round a ring, C at the top; a twelve-note scale's root
    filled and its other notes ringed in the colour; a scale whose steps fall between the notes, or that repeats at
    another interval, as a dot at each step inside the ring (one turn its period), the root filled. Messages: root
    <0..11>, scale <i>."""
    table = ", ".join(f"[[{', '.join(f'{v:.6g}' for v in st)}], {per:.6g}]" for _, st, per in scales)
    names = ", ".join(repr(n) for n in ROOTS)
    return f"""// Tannin's circle. Generated by devices/ideas/tannin/build.py; edit that, not this.
// Messages: root, scale. Draws only.
{HEAD}
var SCALES = [{table}], NAMES = [{names}];
var C = {rgba(color)}, INKC = {rgba(INK)}, TXT = {rgba(TEXT)}, DIMT = {rgba(MUTED, 0.55)}, RING = {rgba(BORDER)};
var FONTN = "{FONT}", rootPc = 9, sc = 2;

function root(r) {{ rootPc = ((Math.floor(r) % 12) + 12) % 12; mgraphics.redraw(); }}
function scale(i) {{ sc = Math.max(0, Math.min(SCALES.length - 1, Math.floor(i))); mgraphics.redraw(); }}

function onNotes() {{
	var st = SCALES[sc][0];
	if (SCALES[sc][1] != 12) return false;
	for (var k = 0; k < st.length; k++) if (Math.abs(st[k] - Math.round(st[k])) > 0.01) return false;
	return true;
}}

function word(x, y, s, size, c) {{
	mgraphics.select_font_face(FONTN);
	mgraphics.set_font_size(size);
	var tw = mgraphics.text_measure(s)[0];
	mgraphics.set_source_rgba(c);
	mgraphics.move_to(x - tw / 2, y);
	mgraphics.show_text(s);
}}

function dot(x, y, r, fill, edge) {{
	mgraphics.ellipse(x - r, y - r, 2 * r, 2 * r);
	mgraphics.set_source_rgba(fill);
	mgraphics.fill();
	if (edge) {{
		mgraphics.ellipse(x - r, y - r, 2 * r, 2 * r);
		mgraphics.set_source_rgba(edge);
		mgraphics.set_line_width(1);
		mgraphics.stroke();
	}}
}}

function paint() {{
	var w = mgraphics.size[0], cx = w / 2, cy = 43, r = 33, named = onNotes(), inScale = {{}};
	var st = SCALES[sc][0], per = SCALES[sc][1];
	mgraphics.set_source_rgba(RING);
	mgraphics.set_line_width(0.8);
	mgraphics.ellipse(cx - r, cy - r, 2 * r, 2 * r);
	mgraphics.stroke();
	if (named) for (var k = 0; k < st.length; k++) inScale[(rootPc + Math.round(st[k])) % 12] = 1;
	for (var pc = 0; pc < 12; pc++) {{
		var a = -Math.PI / 2 + pc / 12 * 2 * Math.PI, x = cx + r * Math.cos(a), y = cy + r * Math.sin(a);
		if (pc == rootPc) {{ dot(x, y, 7, C); word(x, y + 2.6, NAMES[pc], 7, INKC); }}
		else if (inScale[pc]) {{ dot(x, y, 6.2, INKC, C); word(x, y + 2.6, NAMES[pc], 7, TXT); }}
		else word(x, y + 2.6, NAMES[pc], 7, DIMT);
	}}
	if (!named) {{
		for (var k = 0; k < st.length; k++) {{
			var a = -Math.PI / 2 + (rootPc + st[k] * 12 / per) / 12 * 2 * Math.PI;
			dot(cx + (r - 11) * Math.cos(a), cy + (r - 11) * Math.sin(a), k == 0 ? 2.4 : 1.6, C);
		}}
	}}
}}

// for the tests: [drawn on the twelve notes (1) or as steps (0), the pitch classes (or steps) shown]
function values() {{
	var st = SCALES[sc][0], out = [];
	if (onNotes()) {{
		for (var k = 0; k < st.length; k++) out.push((rootPc + Math.round(st[k])) % 12);
		out.sort(function (a, b) {{ return a - b; }});
		return [1, out];
	}}
	return [0, st];
}}
"""


