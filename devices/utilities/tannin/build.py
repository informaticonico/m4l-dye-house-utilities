def key_words(p, x=2600, y=100):
    """ON TANNIN KEY: 'devices play A Minor', from the key as sent (key-pak), unless a second Tannin's warning is
    showing (kn-gate shut)."""
    p.obj("kn-un", "unpack 0 0", 1, 2, x, y)
    p.line("key-t", "kn-un", 2, 0)
    p.obj("kn-sn", "expr $i1+1", 1, 1, x + 60, y + 30)
    p.line("kn-un", "kn-sn", 1, 0)
    p.obj("kn-sg", f"gate {len(SCALES)}", 2, len(SCALES), x, y + 90)
    p.line("kn-sn", "kn-sg", 0, 0)
    p.obj("kn-rsel", "sel " + " ".join(str(i) for i in range(12)), 2, 13, x, y + 60)
    p.line("kn-un", "kn-rsel", 0, 0)
    for i, name in enumerate(ROOTS):
        p.msg(f"kn-r{i}", name, x + 30 * i, y + 75)
        p.line("kn-rsel", f"kn-r{i}", i, 0)
        p.line(f"kn-r{i}", "kn-sg", 0, 1)
    p.obj("kn-gate", "gate 1 1", 2, 1, x, y + 150)
    for i, name in enumerate(SCALE_NAMES):
        p.msg(f"kn-n{i}", f"set devices play $1 {name}", x + 40 * i, y + 120)
        p.line("kn-sg", f"kn-n{i}", i, 0)
        p.line(f"kn-n{i}", "kn-gate", 0, 1)
    p.line("kn-gate", "key-line")


def build_patcher():
    p = Patch(WIDTH)
    background(p, WIDTH, "Tannin", "key", VERSION, sub_color=BLUE)
    box_of(p, "version")["fontsize"] = 7.0                      # no word under 7 px
    panelg.card(p, "key", [X0, 4, WIDTH - 4 - X0, 161], BLUE, "KEY", note="THE WHOLE SET'S KEY")
    # ROOT and SCALE: value columns, Live's live.menus laid over them
    menu(p, "root", "Root", ROOT_COL, ROOTS, 9, 40)
    menu(p, "scale", "Scale", SCALE_COL, SCALE_NAMES, 2, 120)
    for var, label, rect, k in (("root", "ROOT", ROOT_COL, 9), ("scale", "SCALE", SCALE_COL, 2)):
        v = box_of(p, var)["saved_attribute_attributes"]["valueof"]
        item = dict(v=var, l=label, f="menu", lo=0, hi=len(v["parameter_enum"]) - 1, d=k,
                    items=[str(i) for i in v["parameter_enum"]])
        js = embed_script(p, f"{var}-col", rect, panelg.columns_script(
            f"Tannin's {label}", BLUE, [item], source="devices/ideas/tannin/build.py", value_size=12), 2800, 1300)
        panelg.lay(box_of(p, var))
        panelg.feed(p, var, var, js, 2800 + 100 * (var == "scale"))
    # LIVE'S KEY: Live's scale in purple (amber when the family lacks it), what devices on Live key play; FROM LIVE
    lx, ly, lw, lh = LIVE_SCR
    panelg.screen(p, "live-scr", LIVE_SCR)
    panelg.text(p, "live-cap", "LIVE'S KEY", lx + 5, ly + 10, 7, MUTED)
    panelg.text(p, "live-mode", "SCALE MODE OFF", lx + lw - 4, ly + 10, 7, MUTED, anchor="end", w=90)
    panelg.text(p, "live", "C Major", lx + 5, ly + 24, 11, MUTED, w=lw - 10)
    toggle(p, "fromlive", "From Live", [lx + 5, ly + 31, 70, 15], LIVE_C, 700, mode=0, text="FROM LIVE", gated=False)
    box_of(p, "fromlive").update(bgcolor=list(INK), activebgcolor=list(INK), fontsize=7.5, rounded=7.5)
    panelg.text(p, "live-plays", "Key Live plays its own", lx + 81, ly + 41.5, 7, MUTED, w=lw - 84)
    # the key on a circle (any EDO's steps as dots), and its size
    panelg.screen(p, "circle-scr", CIRCLE_SCR)
    cx, cy, cw, ch = CIRCLE_SCR
    circle = embed_script(p, "circle", [cx, cy, cw, 84], circle_script(BLUE, SCALES), 2400, 100)
    panelg.text(p, "steps", "7 notes an octave", cx + cw / 2, cy + 92, 7, MUTED, anchor="middle", w=cw - 4)
    # TUNING; ON TANNIN KEY (or a second Tannin's warning)
    fx, fy, fw, fh = FOOT_SCR
    panelg.screen(p, "foot-scr", FOOT_SCR)
    panelg.text(p, "tuning-cap", "TUNING", fx + 5, fy + 11, 7, MUTED)
    panelg.text(p, "tuning", "none loaded (Live 12.1's tuning systems show here)", fx + 48, fy + 11, 7, TEXT,
                w=fw - 52)
    panelg.text(p, "key-cap", "ON TANNIN KEY", fx + 5, fy + 32, 7, MUTED, w=80)
    panelg.text(p, "key-line", "devices play A Minor", fx + 80, fy + 32, 8, BLUE, w=fw - 84)
    # root, scale -> 'root scale' on the bus, kept in the shared value too
    p.obj("key-pak", "pak 0 0", 2, 1, 40, 100)
    p.line("root", "key-pak", 0, 0)
    p.obj("scale-t", "t i i", 1, 2, 120, 70)
    p.line("scale", "scale-t")
    p.line("scale-t", "key-pak", 1, 1)
    p.obj("key-t", "t l l l", 1, 3, 40, 130)
