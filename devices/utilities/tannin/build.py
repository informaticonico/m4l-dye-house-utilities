"""Build Tannin.amxd: one key for the whole Dye House.

    python3 build.py

Tannin fixes a mordant in the cloth; this fixes the key across a set. Set Root and Scale
(the family's twenty, microtonal ones included) and every family device whose Key is set to
Tannin plays in that key (the others play their own key, or Live's). Put it anywhere, on any MIDI track: MIDI passes
through untouched.

Tannin never writes to Live and never changes itself: it shows Live's current scale (the one
above the tracks) and what devices set to Key Live play, and FROM LIVE copies it into Tannin's menus when
you press it (one undo step, yours). It shows Live 12.1's tuning system if one is loaded, and
warns when a second Tannin is in the set. As it leaves the set it sends 'gone', so followers
stop using its key; a Tannin that hears another leave sends its own key again (and keeps it in
the value), so followers play the key of the one that's left.

On the bus (lib/kit.py): every change goes out as 'root scale' on dyehouse_key and is kept
in 'value dyehouse_key' for devices that start following later. A 'root scale' arriving on
dyehouse_set (Dye Lot's SET) changes Tannin's own menus, which then send it on. One Tannin
per set: two would take turns.

The panel (v1.0b1, the owner, Oct 15: plans/ideas/utilities-panels.md): the probes' panel G, 330 px, the card in
Tannin's blue (its key is the blue one everywhere else). ROOT and SCALE as value columns (Live's live.menus laid
transparent over them: lib/panelg.py); LIVE'S KEY in Live's purple (amber: a Live scale the family lacks) with FROM
LIVE; the key on a circle; TUNING; ON TANNIN KEY, the key every follower plays, where a second Tannin's warning shows
while it lasts. No follower count: it would change every device that follows Tannin (the owner, Oct 15).
"""

