def others(p):
    """One Tannin per set: each says 'here N' as it loads (N a random id), the others answer
    'also M'; hearing another id shows the warning, its 'gone' clears it and sends this one's key
    again, on the bus and in the value, over the 'gone' the other left there. Leaving the set:
    'gone' on dyehouse_key first, then 'gone N', so a Tannin still in the set has the last word.
    The warning takes the ON TANNIN KEY line while it lasts (its key shows there again after)."""
    x = 1800
    p.obj("tn-td", "live.thisdevice", 1, 3, x, 40)
    p.obj("tn-rand", "random 1000000", 2, 1, x, 70)
    p.line("tn-td", "tn-rand")
    p.obj("tn-id", "t i i i i i i", 1, 6, x, 100)
    p.line("tn-rand", "tn-id")
    p.obj("tn-own", "i", 2, 1, x + 200, 130)
    p.line("tn-id", "tn-own", 5, 1)
    p.obj("tn-s", f"s {TANNIN}", 1, 0, x, 250)
    p.msg("tn-here", "here $1", x, 130)
    p.line("tn-id", "tn-here", 0, 0)
    p.line("tn-here", "tn-s")
    p.obj("tn-r", f"r {TANNIN}", 0, 1, x + 300, 40)
    p.obj("tn-route", "route here also gone", 2, 4, x + 300, 70)
    p.line("tn-r", "tn-route")
    for k, kind in enumerate(("here", "also", "gone")):
        p.obj(f"tn-{kind}-x", "expr $i1!=$i2", 2, 1, x + 300 + 100 * k, 100)
        p.line("tn-route", f"tn-{kind}-x", k, 0)
        p.line("tn-id", f"tn-{kind}-x", 3 - k, 1)
