"""Warp's and Weft's screens (scripts packed inside the devices, lib/visual.py's pattern), v1.0b1's panel
(plans/ideas/utilities-panels.md): what the cable carries, as words, and each held note's expression. The keyboard of
the notes going through is lib/visual.py's keyboard_script; the cable selector is lib/panelg.py's cable_tab.

Messages to both: note <pitch> <velocity> [channel] (0 lets it go), flush (a new cable: nothing held), cable <0..3>
(A-D). The status of a Weft also takes warps <n> (how many Warps are on its cable: Warp keeps the count in 'value
dyehouse_warps_X' and sends it down the cable as it changes). The expression screen takes bend <0..16383> <ch>,
press <0..127> <ch> and cc <value> <number> <ch> (74: timbre). Draws only. No word under 7 px.
"""

from m4l import FONT, INK, MUTED, TEXT
from visual import HEAD, SCREEN, rgba

NAMES = '["C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"]'

COMMON = """
var held = [], LETTERS = "ABCD", which = 0;

// a note on or off: the held notes in the order they came ([pitch, channel])
function note(p, v, ch) {
	p = Math.round(p);
	ch = ch === undefined ? 1 : Math.round(ch);
	for (var k = held.length - 1; k >= 0; k--) if (held[k][0] == p && held[k][1] == ch) held.splice(k, 1);
	if (v > 0) held.push([p, ch]);
	mgraphics.redraw();
}

function flush() {
	held = [];
	mgraphics.redraw();
}

function name(p) { return NAMES[((p % 12) + 12) % 12] + (Math.floor(p / 12) - 2); }

function word(x, y, s, size, c, anchor) {
	mgraphics.select_font_face(FONTN);
	mgraphics.set_font_size(size);
	var tw = mgraphics.text_measure(s)[0];
	mgraphics.set_source_rgba(c);
	mgraphics.move_to(anchor == 1 ? x - tw / 2 : (anchor == 2 ? x - tw : x), y);
	mgraphics.show_text(s);
	return tw;
}

function ground(w, h) {
	mgraphics.set_source_rgba(SCREENC);
	mgraphics.rectangle_rounded(0, 0, w, h, 6, 6);
	mgraphics.fill();
}
"""


def status_script(title, color, side):
    """What the cable carries, in words. side 'warp': SENDING, the notes held and that each goes with its own
    expression. side 'weft': THE SENDER: 'Warp A: playing' or 'quiet', 'no Warp on A', '2 Warps on A' (warps <n>),
    the notes held, and that the track's own MIDI plays as well."""
    weft = side == "weft"
    return f"""// {title}. Generated by devices/ideas/warp-weft/screens.py; edit that, not this.
// Messages: note, flush, cable{', warps' if weft else ''}. Draws only.
{HEAD}
var C = {rgba(color)}, SCREENC = {rgba(SCREEN)}, TXT = {rgba(TEXT)}, DIMT = {rgba(MUTED)}, OFF = {rgba(MUTED, 0.5)};
var NAMES = {NAMES}, FONTN = "{FONT}", WEFT = {1 if weft else 0}, warpsOn = 0;
{COMMON}
function cable(i) {{
	which = Math.max(0, Math.min(3, Math.floor(i)));
	flush();
}}

function warps(n) {{
	warpsOn = Math.max(0, Math.floor(n));
	mgraphics.redraw();
}}

// the held notes' names, as many as fit in w at size (the rest as +n)
function names(w, size) {{
	mgraphics.select_font_face(FONTN);
	mgraphics.set_font_size(size);
	var s = "";
	for (var k = 0; k < held.length; k++) {{
		var next = (s ? s + " " : "") + name(held[k][0]), more = held.length - k - 1;
		var tail = more > 0 ? " +" + more : "";
		if (mgraphics.text_measure(next + tail)[0] > w) return s + " +" + (held.length - k);
		s = next;
	}}
	return s;
}}

function heldWords() {{
	var n = held.length;
	return n == 1 ? "1 note held" : n + " notes held";
}}

// the lines shown: [the lamp lit (1) or not (0) or out (-1), line 1, line 2, line 3 (in colour: the names)]
function lines() {{
	var L = LETTERS.charAt(which), n = held.length;
	if (!WEFT) return [n > 0 ? 1 : 0, n > 0 ? heldWords() : "nothing held", "", n > 0 ? "names" : "play on this track"];
	if (warpsOn == 0 && n == 0) return [-1, "no Warp on " + L, "nothing arrives", "put a Warp on " + L];
	var who = warpsOn > 1 ? warpsOn + " Warps on " + L : (warpsOn == 1 ? "Warp " + L : "cable " + L);
	if (warpsOn > 1) return [n > 0 ? 1 : 0, who, n > 0 ? heldWords() : "quiet", n > 0 ? "names" : "both play here"];
	return [n > 0 ? 1 : 0, who + (n > 0 ? ": playing" : ": quiet"), n > 0 ? heldWords() : "nothing held",
		n > 0 ? "names" : ""];
}}

function paint() {{
	var w = mgraphics.size[0], h = mgraphics.size[1], ls = lines();
	ground(w, h);
	word(5, 11, WEFT ? "THE SENDER" : "SENDING", 7, DIMT, 0);
	mgraphics.set_source_rgba(ls[0] > 0 ? C : OFF);
	mgraphics.ellipse(5.8, 20.8, 6.4, 6.4);
	mgraphics.fill();
	word(17, 27, ls[1], 8, ls[0] < 0 || (!WEFT && held.length == 0) ? DIMT : TXT, 0);
	if (ls[2]) word(5, 44, ls[2], 8, ls[0] < 0 || (held.length == 0) ? DIMT : TXT, 0);
	var y3 = WEFT ? 57 : 41;
	if (ls[3] == "names") word(5, y3, names(w - 10, 8), 8, C, 0);
	else if (ls[3]) word(5, y3, ls[3], 7, DIMT, 0);
	if (WEFT) {{
		word(5, h - 25, "+ this track's own MIDI", 7, DIMT, 0);
		word(5, h - 13, "plays as well", 7, DIMT, 0);
	}} else {{
		word(5, h - 20, "each on its own channel,", 7, DIMT, 0);
		word(5, h - 11, "with its own bend,", 7, DIMT, 0);
		word(5, h - 2.5, "pressure and timbre", 7, DIMT, 0);
	}}
}}

// for the tests: [notes held, line 1, line 2, line 3 (the names, as shown)]
function values() {{
	var ls = lines();
	return [held.length, ls[1], ls[2], ls[3] == "names" ? names(1000, 8) : ls[3]];
}}
"""


def expression_script(title, color, slots=4):
    """A slot a held note (the first `slots`, in the order they came; a fifth and more as '+n' in the last slot):
    its name over three bars, bend (from the middle), pressure and timbre (CC 74), each its channel's as it arrives."""
    return f"""// {title}. Generated by devices/ideas/warp-weft/screens.py; edit that, not this.
// Messages: note, flush, cable, bend, press, cc. Draws only.
{HEAD}
var C = {rgba(color)}, SCREENC = {rgba(SCREEN)}, TXT = {rgba(TEXT)}, DIMT = {rgba(MUTED)}, WELL = {rgba(INK, 1)};
var CELLC = [0.227451, 0.227451, 0.211765, 1], NAMES = {NAMES}, FONTN = "{FONT}", SLOTS = {slots};
var BEND = {{}}, PRESS = {{}}, TIMBRE = {{}};
{COMMON}
function cable(i) {{ flush(); }}
function bend(v, ch) {{ BEND[Math.round(ch)] = (v - 8192) / 8192; mgraphics.redraw(); }}
function press(v, ch) {{ PRESS[Math.round(ch)] = v / 127; mgraphics.redraw(); }}
function cc(v, n, ch) {{ if (Math.round(n) == 74) {{ TIMBRE[Math.round(ch)] = v / 127; mgraphics.redraw(); }} }}

function get(o, ch, d) {{ return o.hasOwnProperty(ch) ? o[ch] : d; }}

// what each slot shows: [name, bend -1..1, pressure 0..1, timbre 0..1] or [name] alone ('—', '+n')
function slots() {{
	var out = [], n = held.length;
	for (var k = 0; k < SLOTS; k++) {{
		if (k == SLOTS - 1 && n > SLOTS) {{ out.push(["+" + (n - SLOTS + 1)]); continue; }}
		if (k >= n) {{ out.push(["\\u2014"]); continue; }}
		var ch = held[k][1];
		out.push([name(held[k][0]), get(BEND, ch, 0), get(PRESS, ch, 0), get(TIMBRE, ch, 0.5)]);
	}}
	return out;
}}

function paint() {{
	var w = mgraphics.size[0], h = mgraphics.size[1], s = slots(), sw = (w - 8) / SLOTS, top = 28, base = h - 13;
	ground(w, h);
	word(5, 10, "EACH NOTE: BEND \\u00b7 PRESSURE \\u00b7 TIMBRE", 7, DIMT, 0);
	for (var k = 0; k < SLOTS; k++) {{
		var x = 4 + k * sw, on = s[k].length > 1;
		word(x + sw / 2, 23, s[k][0], 8, on ? TXT : DIMT, 1);
		for (var j = 0; j < 3; j++) {{
			var bw = (sw - 10) / 3 - 3, bx = x + 5 + j * (sw - 10) / 3;
			mgraphics.set_source_rgba(CELLC);
			mgraphics.rectangle_rounded(bx, top, bw, base - top, 2.4, 2.4);
			mgraphics.fill();
			if (on) {{
				var v = s[k][1 + j];
				mgraphics.set_source_rgba(C);
				if (j == 0) {{
					var mid = (top + base) / 2, a = Math.min(mid, mid - v * (base - top) / 2), b = Math.max(mid, mid - v * (base - top) / 2);
					mgraphics.rectangle(bx, a, bw, Math.max(b - a, 1));
					mgraphics.fill();
					mgraphics.set_source_rgba(TXT);
					mgraphics.set_line_width(0.6);
					mgraphics.move_to(bx - 1, mid);
					mgraphics.line_to(bx + bw + 1, mid);
					mgraphics.stroke();
				}} else if (v > 0) {{
					mgraphics.rectangle(bx, base - (base - top) * v, bw, (base - top) * v);
					mgraphics.fill();
				}}
			}}
			word(bx + bw / 2, h - 3, "BPT".charAt(j), 7, on ? TXT : DIMT, 1);
		}}
	}}
}}

// for the tests: each slot's [name, bend, pressure, timbre] (or [name])
function values() {{ return slots(); }}
"""
