def keyboard_script(title, color, scales=(), octaves=3):
    """A keyboard of `octaves` octaves: the scale's notes marked (scales: lib/scales.py's SCALES,
    whose steps may fall between the keys: those are drawn as ticks where they fall), and the notes
    sounding filled in colour, as bright as they are loud. Messages: scale <i>, root <0..11>,
    octave <o> (where the keyboard starts when nothing sounds: that octave's C), wave <idx>
    <level 1..n> <pitch 1..n> (gen~'s windows: n voices, each's level 0..1 and its MIDI pitch, -1
    silent), note <pitch> <velocity> (a held note: 0 lets it go), flush (every held note let go).
    The keyboard starts at the C at or below the lowest note sounding."""
    table = ", ".join(f"[[{', '.join(f'{v:.6g}' for v in st)}], {per:.6g}]" for _, st, per in scales)
    return f"""// {title}. Generated by lib/visual.py; edit that, not this.
// Messages: scale, root, octave, wave, note, flush. Draws only; no audio.
{HEAD}
var SCALES = [{table}];
var OCTAVES = {octaves};
var C = {rgba(color)}, WHITE = [0.914, 0.902, 0.863, 1], BLACK = [0.137, 0.137, 0.129, 1];
var DOT = {rgba(MUTED)}, SCREEN = {rgba(SCREEN)};
var sc = -1, rootPc = 0, oct = 3, voices = [], held = {{}};

function scale(i) {{
	sc = Math.floor(i);
	mgraphics.redraw();
}}

function root(r) {{
	rootPc = ((Math.floor(r) % 12) + 12) % 12;
	mgraphics.redraw();
}}

function octave(o) {{
	oct = Math.floor(o);
	mgraphics.redraw();
}}

function wave() {{
	var n = Math.floor((arguments.length - 1) / 2);
	voices = [];
	for (var k = 0; k < n; k++) voices.push([arguments[1 + n + k], Math.max(0, Math.min(1, arguments[1 + k]))]);
	mgraphics.redraw();
}}

function note(p, v) {{
	if (v > 0) held[Math.round(p)] = v / 127;
	else delete held[Math.round(p)];
	mgraphics.redraw();
}}

// every note sounding: [pitch, level]
function sounding() {{
	var out = [];
	for (var k = 0; k < voices.length; k++) if (voices[k][0] >= 0) out.push(voices[k]);
	for (var p in held) out.push([Number(p), held[p]]);
	return out;
}}

// the keyboard's lowest C: the one at or below the lowest note sounding, else the set octave's
function base() {{
	var s = sounding(), lo = null;
	for (var k = 0; k < s.length; k++) if (lo === null || s[k][0] < lo) lo = s[k][0];
	return lo === null ? 12 * (oct + 1) : 12 * Math.floor(lo / 12);
}}

// every held note released (a new cable, Rinse)
function flush() {{
	held = {{}};
	mgraphics.redraw();
}}

var WHITE_OF = [0, 0, 1, 1, 2, 3, 3, 4, 4, 5, 5, 6], IS_BLACK = [0, 1, 0, 1, 0, 0, 1, 0, 1, 0, 1, 0];

// x of a pitch's centre, pitches between keys (microtonal) where they fall
function xOf(p, b, ww) {{
	var o = Math.floor((p - b) / 12), pc = p - b - 12 * o, i = Math.floor(pc), f = pc - i;
	function cx(q) {{
		var qo = Math.floor(q / 12), qp = q - 12 * qo;
		return (qo * 7 + WHITE_OF[qp] + (IS_BLACK[qp] ? 1 : 0.5)) * ww;
	}}
	var a = cx(12 * o + i), z = cx(12 * o + i + 1);
	return a + (z - a) * f;
}}

// the scale's pitches (from the root, every octave) in the window
function scaleNotes(b) {{
	var out = [];
	if (sc < 0 || sc >= SCALES.length) return out;
	var st = SCALES[sc][0], per = SCALES[sc][1], lo = b, hi = b + 12 * OCTAVES;
	for (var r = Math.floor((lo - rootPc) / per) - 1; (rootPc + r * per) < hi; r++)
		for (var k = 0; k < st.length; k++) {{
			var p = rootPc + r * per + st[k];
			if (p >= lo && p < hi) out.push(p);
		}}
	return out;
}}

function paint() {{
	var w = mgraphics.size[0], h = mgraphics.size[1], b = base(), nw = 7 * OCTAVES, ww = w / nw;
	var bh = h * 0.6, s = sounding(), marks = scaleNotes(b);
	with (mgraphics) {{
		set_source_rgba(SCREEN);
		rectangle_rounded(0, 0, w, h, 6, 6);
		fill();
		for (var i = 0; i < nw; i++) {{
			set_source_rgba(WHITE);
			rectangle(i * ww + 0.5, 1, ww - 1, h - 2);
			fill();
		}}
		// notes sounding on white keys
		for (var k = 0; k < s.length; k++) {{
			var p = s[k][0], q = Math.round(p);
			if (Math.abs(p - q) > 0.05 || IS_BLACK[((q - b) % 12 + 12) % 12] || q < b || q >= b + 12 * OCTAVES) continue;
			var o = Math.floor((q - b) / 12), wi = o * 7 + WHITE_OF[q - b - 12 * o];
			set_source_rgba(C[0], C[1], C[2], 0.25 + 0.75 * s[k][1]);
			rectangle(wi * ww + 0.5, 1, ww - 1, h - 2);
			fill();
		}}
		for (var o = 0; o < OCTAVES; o++)
			for (var pc = 0; pc < 12; pc++) {{
				if (!IS_BLACK[pc]) continue;
				var x = (o * 7 + WHITE_OF[pc] + 1) * ww - ww * 0.3;
				set_source_rgba(BLACK);
				rectangle(x, 1, ww * 0.6, bh);
				fill();
			}}
		// notes sounding on black keys, and between the keys
		for (var k = 0; k < s.length; k++) {{
			var p = s[k][0], q = Math.round(p);
			if (p < b || p >= b + 12 * OCTAVES) continue;
			var micro = Math.abs(p - q) > 0.05, blk = IS_BLACK[((q - b) % 12 + 12) % 12];
			if (!micro && !blk) continue;
			set_source_rgba(C[0], C[1], C[2], 0.25 + 0.75 * s[k][1]);
			var x = xOf(p, b, ww);
			if (micro) rectangle(x - 1.5, 1, 3, h - 2);
			else rectangle(x - ww * 0.3, 1, ww * 0.6, bh);
			fill();
		}}
		// the scale's notes: a dot at the foot of each (a tick where it falls between keys)
		set_source_rgba(DOT);
		for (var k = 0; k < marks.length; k++) {{
			var p = marks[k], q = Math.round(p), x = xOf(p, b, ww);
			var blk = Math.abs(p - q) <= 0.05 && IS_BLACK[((q - b) % 12 + 12) % 12];
			ellipse(x - 1.5, (blk ? bh : h) - 5, 3, 3);
			fill();
		}}
	}}
}}

// for the tests: [the lowest C, the scale's notes shown, the notes sounding as [pitch, level]..]
function values() {{
	var b = base();
	return [b, scaleNotes(b), sounding()];
}}
"""


